def test_title_present(minimal_report_data):
    """
    Test that main Arabic title is present in document.
    """
    doc_bytes = generate_action_log_word(minimal_report_data)
    doc = Document(BytesIO(doc_bytes))
    
    # Find title in paragraphs
    title_found = False
