# TEST 1 — RETURNS BYTES
# ============================================================================

def test_returns_bytes(minimal_report_data):
    """
    Test that generator returns bytes object with reasonable size.
    """
    doc_bytes = generate_action_log_word(minimal_report_data)
    
    # Assert it's bytes
    assert isinstance(doc_bytes, bytes)
    
    # Assert reasonable size (Word docs are typically > 1KB)
    assert len(doc_bytes) > 1000
    
    print(f"✅ Generated Word document: {len(doc_bytes)} bytes")


# ============================================================================
# TEST 2 — OPENS WITH PYTHON-DOCX
# ============================================================================

def test_opens_with_python_docx(minimal_report_data):
    """
    Test that generated bytes can be opened as a valid Word document.
    """
    doc_bytes = generate_action_log_word(minimal_report_data)
    
    # Should not raise exception
    doc = Document(BytesIO(doc_bytes))
    
    # Basic validation
    assert doc is not None
    assert len(doc.paragraphs) > 0
    
    print(f"✅ Document opened successfully with {len(doc.paragraphs)} paragraphs")


