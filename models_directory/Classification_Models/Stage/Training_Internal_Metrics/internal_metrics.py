def predict_sentence_metrics(text, top_k=13, Troubleshoot = False):
    METRICS = [
        "administration_delay",
        "arrival",
        "bed_room",
        "billing_issues",
        "cleanliness",
        "clinical_delay",
        "communication_scheduling",
        "conflicting_or_wrong_diagnosis",
        "disagreement_with_discharge",
        "food",
        "location",
        "medical_clinical_errors",
        "staff_security_behavior"
    ]
    BASE_DIR = os.path.dirname(os.path.abspath(__file__))
    MODEL_ROOT = os.path.join(BASE_DIR, "vocab_models")
    """
    Takes raw text, embeds + normalizes it,
    runs it through all metric vocab_models,
    and prints top_k metrics sorted by probability.
    """

    # --------------------------------------------
    # 1) Embed the sentence
    # --------------------------------------------
    emb = get_embedding(text)

    # convert bytes if necessary (like your normal pipeline)
    if isinstance(emb, bytes):
        emb = np.frombuffer(emb, dtype=np.float32)

    vector = l2_normalize(emb)

    results = []

    # --------------------------------------------
    # 2) Loop over each metric directory
    # --------------------------------------------
    for metric in METRICS:
        model_dir = os.path.join(MODEL_ROOT, metric)

        if not os.path.exists(model_dir):
            print(f"[WARN] No folder for metric: {metric}")
            continue

        # load possible vocab_models
        model_files = {
            "lr": os.path.join(model_dir, f"{metric}_lr.pkl"),
            "rf": os.path.join(model_dir, f"{metric}_rf.pkl"),
            "xgb": os.path.join(model_dir, f"{metric}_xgb.pkl"),
        }

        preds = []

        # --------------------------------------------
        # 3) Predict using LR / RF / XGB if found
        # --------------------------------------------
        for name, path in model_files.items():
            if os.path.exists(path):
                model = joblib.load(path)
                prob = model.predict_proba([vector])[0][1]
                preds.append(prob)

        if len(preds) == 0:
            print(f"[WARN] No vocab_models found for metric: {metric}")
            continue

        # final score average
        score = sum(preds) / len(preds)
        results.append((metric, score))

    # --------------------------------------------
    # 4) Sort scores descending
    # --------------------------------------------
    results.sort(key=lambda x: x[1], reverse=True)

    # --------------------------------------------
    # 5) Print the top metrics
    # --------------------------------------------
    if Troubleshoot:
        print("\n==============================")
        print(f"Results for: {text}")
        print("==============================")
        for metric, score in results[:top_k]:
            print(f"{metric:<35} → {score:.4f}")


    return results[:top_k]

def predict_metrics_from_embedding(normalized_vec):
    METRICS = [
        "administration_delay",
        "arrival",
        "bed_room",
        "billing_issues",
        "cleanliness",
        "clinical_delay",
        "communication_scheduling",
        "conflicting_or_wrong_diagnosis",
        "disagreement_with_discharge",
        "food",
        "location",
        "medical_clinical_errors",
        "staff_security_behavior"
    ]

    # Fix: resolve absolute path like in predict_sentence_metrics
    BASE_DIR = os.path.dirname(os.path.abspath(__file__))
    MODEL_ROOT = os.path.join(BASE_DIR, "vocab_models")

    results = []

    for metric in METRICS:
        model_dir = os.path.join(MODEL_ROOT, metric)
        if not os.path.exists(model_dir):
            continue

        model_files = {
            "lr": os.path.join(model_dir, f"{metric}_lr.pkl"),
            "rf": os.path.join(model_dir, f"{metric}_rf.pkl"),
            "xgb": os.path.join(model_dir, f"{metric}_xgb.pkl"),
        }

        preds = []
        for _, path in model_files.items():
            if os.path.exists(path):
                model = joblib.load(path)
                prob = model.predict_proba([normalized_vec])[0][1]
                preds.append(prob)

        if len(preds) == 0:
            continue

        score = sum(preds) / len(preds)
        results.append((metric, score))

    results.sort(key=lambda x: x[1], reverse=True)
    return results


def split_max_score(paragraph: str, Troubleshoot=False) -> Tuple[List[Tuple[str, float]], Dict[int, Dict[str, float]]]:
    _METRIC_EMB_PATH = os.path.join("model_storage", "metric_embeddings.json")

    # -----------------------------
    # Load precomputed metric embeddings if available
    # -----------------------------
    if os.path.exists(_METRIC_EMB_PATH):
        with open(_METRIC_EMB_PATH, "r", encoding="utf-8") as _mf:
            _METRIC_EMB = {k: np.array(v, dtype=np.float32) for k, v in json.load(_mf).items()}
        for k in _METRIC_EMB.keys():
            _METRIC_EMB[k] = l2_normalize(_METRIC_EMB[k])
    else:
        _METRIC_EMB = {}

    if paragraph is None:
        paragraph = ""

    # -----------------------------
    # Split into sentences / segments
    # -----------------------------
    try:
        segments = split_arabic_text_into_sentences(paragraph)
    except TypeError:
        segments = [paragraph]

    segments = segments[:6] if isinstance(segments, list) else [segments]
    cleaned_segments = [s.strip() for s in segments if s and s.strip()]
    if not cleaned_segments and paragraph.strip():
        cleaned_segments = [paragraph.strip()]

    # -----------------------------
    # Embed all segments at once
    # -----------------------------
    embeddings_bytes_list = get_embedding_list(cleaned_segments, Troubleshoot=Troubleshoot)

    per_segment_scores = {}
    metric_max = {k: -1.0 for k in _METRIC_EMB.keys()}

    # -----------------------------
    # Predict metrics for each segment using embedding
    # -----------------------------
    for idx, (seg, emb_bytes) in enumerate(zip(cleaned_segments, embeddings_bytes_list), start=1):
        try:
            emb = np.frombuffer(emb_bytes, dtype=np.float32)
            vector = l2_normalize(emb)
            raw_scores = predict_metrics_from_embedding(vector)  # returns list of (metric, score)
            seg_scores = {m: s for m, s in raw_scores}
        except Exception:
            seg_scores = {k: 0.0 for k in _METRIC_EMB.keys()}

        per_segment_scores[idx] = seg_scores

        # Keep track of max score per metric across segments
        for m, sc in seg_scores.items():
            if sc > metric_max.get(m, -1.0):
                metric_max[m] = float(sc)

    sorted_metrics = sorted(metric_max.items(), key=lambda kv: kv[1], reverse=True)
    return sorted_metrics, per_segment_scores






